export const normalizeVehicleIdentity = (value) => String(value || '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
const brandAliases = { mercedes: 'Mercedes-Benz', benz: 'Mercedes-Benz', vw: 'Volkswagen' };
const knownBrands = new Map(Object.keys(vehicleClassificationMap).map(brand => [normalizeVehicleIdentity(brand), brand]));
export function canonicalVehicleIdentity(brand, model) {
  const brandKey = normalizeVehicleIdentity(brand);
  const canonicalBrand = knownBrands.get(brandKey) || (Object.hasOwn(brandAliases, brandKey) ? brandAliases[brandKey] : '') || String(brand || '').trim();
  const models = Object.hasOwn(vehicleClassificationMap, canonicalBrand) ? vehicleClassificationMap[canonicalBrand] : {};
  const canonicalModel = Object.keys(models).find(name => normalizeVehicleIdentity(name) === normalizeVehicleIdentity(model));
  return { brand: canonicalBrand, model: canonicalModel || String(model || '').trim() };
}
export function resolveVehicleClassification(brand, model) {
  const canonical = canonicalVehicleIdentity(brand, model);
  if (!Object.hasOwn(vehicleClassificationMap, canonical.brand)) return null;
  const models = vehicleClassificationMap[canonical.brand];
  return Object.hasOwn(models, canonical.model) ? models[canonical.model] : null;
}
